import 'dart:convert';
import 'dart:io';

void main() {
  final levelsDir = Directory('assets/data/levels');
  if (!levelsDir.existsSync()) {
    levelsDir.createSync(recursive: true);
  }

  // 1. Process Chapter 1 (from dhaka.json if exists)
  _convertOldFile('assets/data/levels/dhaka.json', 'assets/data/levels/chapter_1.json', 'অধ্যায় ১', 'chapter_1', 1, 20);

  // 2. Process Chapter 2 (from chittagong.json if exists)
  _convertOldFile('assets/data/levels/chittagong.json', 'assets/data/levels/chapter_2.json', 'অধ্যায় ২', 'chapter_2', 21, 40);

  // 3. Process Chapter 3 (from sylhet.json if exists)
  _convertOldFile('assets/data/levels/sylhet.json', 'assets/data/levels/chapter_3.json', 'অধ্যায় ৩', 'chapter_3', 41, 60);

  // 4. Generate Chapter 4 (Levels 61-80) - ফলমূল ও ঋতুরাজ
  _generateChapter4();

  // 5. Generate Chapter 5 (Levels 81-100) - বন্যপ্রাণী ও সুন্দরবন
  _generateChapter5();

  // 6. Generate Chapter 6 (Levels 101-120) - নদীমাতৃক ও পালতোলা
  _generateChapter6();

  // 7. Generate Chapter 7 (Levels 121-140) - সোনালী ধান ও পল্লীগান
  _generateChapter7();

  // 8. Generate Chapter 8 (Levels 141-160) - শিল্প, সুর ও সংস্কৃতি
  _generateChapter8();

  // Remove old division files
  for (final oldFile in ['dhaka.json', 'chittagong.json', 'sylhet.json']) {
    final f = File('assets/data/levels/$oldFile');
    if (f.existsSync()) {
      f.deleteSync();
      print('Deleted old division file: $oldFile');
    }
  }

  print('All 8 chapters generated successfully!');
}

void _convertOldFile(String oldPath, String newPath, String chapterName, String chapterKey, int startId, int endId) {
  final oldFile = File(oldPath);
  if (!oldFile.existsSync()) return;

  final data = jsonDecode(oldFile.readAsStringSync()) as Map<String, dynamic>;
  final levels = (data['levels'] as List).map((l) {
    final map = Map<String, dynamic>.from(l as Map);
    map['division'] = chapterName;
    return map;
  }).toList();

  final newContent = {
    'division': chapterName,
    'divisionKey': chapterKey,
    'levels': levels,
  };

  File(newPath).writeAsStringSync(const JsonEncoder.withIndent('  ').convert(newContent));
  print('Saved $newPath with ${levels.length} levels');
}

